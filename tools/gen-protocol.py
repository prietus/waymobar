#!/usr/bin/env python3
"""Generate src/Waymobar/Wayland/Protocol.hs from the XML files in protocol/.

Usage: tools/gen-protocol.py IFACES protocol/*.xml > src/Waymobar/Wayland/Protocol.hs

IFACES is a comma separated list of the interfaces to generate (the XML files
define many more than waymobar uses). For every interface it emits:
  * a sum type with one constructor per event,
  * a decoder from (opcode, payload) to that type,
  * one function per request that encodes and queues the message,
  * Word32 constants for every enum entry.
Opcodes are the position of the request/event inside its interface, which is
exactly how libwayland's wayland-scanner numbers them.

File descriptors in requests are sent out of band (SCM_RIGHTS) by
Waymobar.Wayland.Wire. File descriptors in events are not supported: the
generator refuses interfaces that would receive one.
"""
import sys
import xml.etree.ElementTree as ET

HS_TYPES = {
    "int": "Int32",
    "uint": "Word32",
    "fixed": "Double",
    "string": "ByteString",
    "object": "ObjectId",
    "new_id": "ObjectId",
    "array": "ByteString",
    "fd": "Fd",
}
GETTERS = {
    "int": "getInt",
    "uint": "getUint",
    "fixed": "getFixed",
    "string": "getStr",
    "object": "getObj",
    "new_id": "getObj",
    "array": "getArray",
}
PUTTERS = {
    "int": "putInt",
    "uint": "putUint",
    "fixed": "putFixed",
    "string": "putString",
    "object": "putObj",
    "array": "putArray",
}


def camel(name, upper):
    parts = name.split("_")
    s = "".join(p[:1].upper() + p[1:] for p in parts)
    return s if upper else s[:1].lower() + s[1:]


def main(wanted, paths):
    wanted = set(wanted.split(","))
    ifaces = []
    for p in paths:
        root = ET.parse(p).getroot()
        ifaces.extend(i for i in root.findall("interface") if i.get("name") in wanted)
    missing = wanted - {i.get("name") for i in ifaces}
    if missing:
        sys.exit(f"interfaces not found: {', '.join(sorted(missing))}")

    out = []
    w = out.append
    w("-- | GENERATED by tools/gen-protocol.py from protocol/*.xml. Do not edit.")
    w("{-# LANGUAGE OverloadedStrings #-}")
    w("{-# OPTIONS_GHC -Wno-unused-imports -Wno-unused-matches #-}")
    w("module Waymobar.Wayland.Protocol where")
    w("")
    w("import Data.ByteString (ByteString)")
    w("import Data.Int (Int32)")
    w("import Data.Word (Word16, Word32)")
    w("import Data.Binary.Get (Get)")
    w("import System.Posix.Types (Fd)")
    w("import Waymobar.Wayland.Wire")
    w("")

    w("-- | Any event from any interface known to waymobar, tagged with its sender.")
    w("data Event")
    first = True
    for i in ifaces:
        if not i.findall("event"):
            continue
        n = camel(i.get("name"), True)
        w(f"  {'=' if first else '|'} Ev{n} !ObjectId !{n}Event")
        first = False
    w("  deriving (Show)")
    w("")
    w("-- | Find the decoder for an event, given the interface name of the sender.")
    w("-- Returns the event and the server-created objects it introduces.")
    w("decodeEvent :: ByteString -> ObjectId -> Word16 -> Maybe (Get (Event, [(ObjectId, ByteString)]))")
    for i in ifaces:
        if not i.findall("event"):
            continue
        n = camel(i.get("name"), True)
        w(f"decodeEvent \"{i.get('name')}\" o op = fmap (\\(e, ns) -> (Ev{n} o e, ns)) <$> decode{n}Event op")
    w("decodeEvent _ _ _ = Nothing")
    w("")

    for i in ifaces:
        iname = i.get("name")
        n = camel(iname, True)
        ln = camel(iname, False)
        w(f"-- * {iname} (version {i.get('version')})")
        w("")
        w(f"{ln}Interface :: ByteString")
        w(f"{ln}Interface = \"{iname}\"")
        w("")
        w(f"{ln}Version :: Word32")
        w(f"{ln}Version = {i.get('version')}")
        w("")

        for e in i.findall("enum"):
            en = camel(e.get("name"), True)
            for entry in e.findall("entry"):
                cn = f"{ln}{en}{camel(entry.get('name'), True)}"
                w(f"{cn} :: Word32")
                w(f"{cn} = {entry.get('value')}")
            w("")

        events = i.findall("event")
        if events:
            w(f"data {n}Event")
            for k, ev in enumerate(events):
                args = ev.findall("arg")
                for a in args:
                    if a.get("type") == "fd":
                        sys.exit(f"fd args in events are not supported: {iname}.{ev.get('name')}")
                fields = " ".join(f"!{HS_TYPES[a.get('type')]}" for a in args)
                w(f"  {'=' if k == 0 else '|'} {n}{camel(ev.get('name'), True)}{(' ' + fields) if fields else ''}")
            w("  deriving (Show)")
            w("")
            w(f"decode{n}Event :: Word16 -> Maybe (Get ({n}Event, [(ObjectId, ByteString)]))")
            for op, ev in enumerate(events):
                args = ev.findall("arg")
                con = f"{n}{camel(ev.get('name'), True)}"
                if not args:
                    w(f"decode{n}Event {op} = Just (pure ({con}, []))")
                    continue
                binds = "; ".join(f"a{k} <- {GETTERS[a.get('type')]}" for k, a in enumerate(args))
                vals = " ".join(f"a{k}" for k in range(len(args)))
                news = ", ".join(
                    f"(a{k}, \"{a.get('interface')}\")"
                    for k, a in enumerate(args)
                    if a.get("type") == "new_id"
                )
                w(f"decode{n}Event {op} = Just (do {{ {binds}; pure ({con} {vals}, [{news}]) }})")
            w(f"decode{n}Event _ = Nothing")
            w("")

        for op, rq in enumerate(i.findall("request")):
            fn = f"{ln}{camel(rq.get('name'), True)}"
            args = rq.findall("arg")
            params, puts, fds, ret_iface = [], [], [], None
            for k, a in enumerate(args):
                t = a.get("type")
                if t == "fd":
                    params.append((f"a{k}", "Fd"))
                    fds.append(f"a{k}")
                    continue
                if t == "new_id":
                    if a.get("interface"):
                        ret_iface = f"\"{a.get('interface')}\""
                        puts.append("putObj newObj")
                    else:
                        params.append(("iface", "ByteString"))
                        params.append(("ver", "Word32"))
                        ret_iface = "iface"
                        puts.append("putString iface <> putUint ver <> putObj newObj")
                    continue
                params.append((f"a{k}", HS_TYPES[t]))
                puts.append(f"{PUTTERS[t]} a{k}")
            ret = "IO ObjectId" if ret_iface else "IO ()"
            sig = " -> ".join(["Conn", "ObjectId"] + [t for _, t in params] + [ret])
            names = " ".join(["c", "self"] + [nm for nm, _ in params])
            body = " <> ".join(puts) if puts else "mempty"
            send = f"sendRequestFds c self {op} [{', '.join(fds)}] ({body})" if fds else f"sendRequest c self {op} ({body})"
            w(f"-- | {iname}.{rq.get('name')} (opcode {op})")
            w(f"{fn} :: {sig}")
            if ret_iface:
                w(f"{fn} {names} = do")
                w(f"  newObj <- newObject c {ret_iface}")
                w(f"  {send}")
                w("  pure newObj")
            elif rq.get("type") == "destructor":
                w(f"{fn} {names} = do")
                w(f"  {send}")
                w("  forgetObject c self")
            else:
                w(f"{fn} {names} = {send}")
            w("")

    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2:])
